// Itinerary geocoding pipeline. Two modes:
//
//   node scripts/geocode-itineraries.mjs --worklist
//       Fetch every timeline in the Google Sheet, run the current coords lookup over
//       each row, and print the rows that DON'T resolve to a precise place — the
//       candidates a human/Claude judges as real-place vs filler.
//
//   node scripts/geocode-itineraries.mjs
//       Geocode scripts/itinerary-queries.json via the Google Maps Geocoding API
//       (key from japan2026/.env → VITE_GOOGLE_MAP), validate each result is inside
//       Japan, and (re)write shared/data/itineraryGeocoded.js + copy to both apps.
//
// Requires Node 22 (nvm use 22). See CLAUDE.md → "Geocoding itinerary places".
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const P = (...p) => path.join(ROOT, ...p);
const Papa = (await import(P('japan2026/node_modules/papaparse/papaparse.min.js'))).default;
const { parseTimelineCSV } = await import(P('japan2026/src/utils.js'));
const { ITINERARIES } = await import(P('shared/data/itineraries.js'));
const { AREA_COORDS, getScheduleCoord } = await import(P('shared/data/coords.js'));
const { ITINERARY_COORDS } = await import(P('shared/data/restaurantCoords.js'));

const SHEET_ID = '1N_V9v7uKz3hXRQSnVNaaeAJO7vgU-GdnE5Pisln6C1A';
const CITY_KEYS = new Set(['Tokyo', 'Osaka', 'Kyoto', 'Kinosaki', 'Hakone']);

async function fetchDays(gid) {
  const csv = await (await fetch(`https://docs.google.com/spreadsheets/d/${SHEET_ID}/gviz/tq?tqx=out:csv&gid=${gid}`)).text();
  return parseTimelineCSV(Papa.parse(csv, { header: false, skipEmptyLines: false }).data) || [];
}

async function worklist() {
  const itinKeys = Object.keys(ITINERARY_COORDS);
  const areaKeys = Object.keys(AREA_COORDS);
  const tier = (a) => {
    const s = a.toLowerCase();
    if (itinKeys.some((k) => s.includes(k.toLowerCase()))) return 'exact';
    const hit = areaKeys.find((k) => s.includes(k.toLowerCase()));
    if (hit && !CITY_KEYS.has(hit)) return 'area';
    return hit ? 'city' : 'none';
  };
  const seen = new Map();
  for (const it of ITINERARIES) {
    for (const d of await fetchDays(it.gid)) {
      for (const s of d.schedule || []) {
        const t = tier(s.activity);
        if (t === 'exact' || t === 'area') continue;
        const text = (s.activity || '').split('\n')[0].replace(/https?:\/\/\S+/g, '').replace(/\s{2,}/g, ' ').trim();
        if (text && !seen.has(text)) seen.set(text, `${t} (${d.location || '?'})`);
      }
    }
  }
  console.log(`# ${seen.size} unresolved candidate rows — judge real-place vs filler:\n`);
  [...seen.entries()].sort().forEach(([t, meta]) => console.log(`[${meta}] ${t}`));
}

async function geocode() {
  const env = fs.readFileSync(P('japan2026/.env'), 'utf8');
  const KEY = (env.match(/^VITE_GOOGLE_MAP=(.*)$/m) || [])[1]?.trim().replace(/^['"]|['"]$/g, '');
  if (!KEY) throw new Error('VITE_GOOGLE_MAP not found in japan2026/.env');
  const queries = JSON.parse(fs.readFileSync(P('scripts/itinerary-queries.json'), 'utf8'));
  const inJapan = (lat, lng) => lat >= 24 && lat <= 46 && lng >= 122 && lng <= 154;

  const out = {}, fails = [];
  for (const [key, query] of Object.entries(queries)) {
    const url = `https://maps.googleapis.com/maps/api/geocode/json?address=${encodeURIComponent(query)}&key=${KEY}&region=jp&language=en`;
    try {
      const d = await (await fetch(url)).json();
      const r = d.results && d.results[0];
      if (d.status !== 'OK' || !r) { fails.push(`${key} [${d.status}]`); continue; }
      const { lat, lng } = r.geometry.location;
      if (!inJapan(lat, lng)) { fails.push(`${key} [outside Japan]`); continue; }
      out[key] = [Math.round(lat * 1e6) / 1e6, Math.round(lng * 1e6) / 1e6];
    } catch (e) { fails.push(`${key} [${e.message}]`); }
  }

  const esc = (k) => k.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  const body = [
    '// Itinerary place coordinates resolved via the Google Maps Geocoding API.',
    '// GENERATED by scripts/geocode-itineraries.mjs — see CLAUDE.md → "Geocoding itinerary places".',
    '// Keys are substrings that appear in Google-Sheet timeline activity cells; getScheduleCoord',
    '// (coords.js) matches an activity to a coordinate by testing whether it contains one of these keys.',
    '// Filler rows (dinner, nap, laundry, transit, "choose your adventure") are intentionally absent.',
    '',
    'export const ITINERARY_GEOCODED = {',
    ...Object.entries(out).map(([k, v]) => `  '${esc(k)}': [${v[0]}, ${v[1]}],`),
    '};',
    '',
  ].join('\n');

  for (const rel of ['shared/data/itineraryGeocoded.js', 'japan2026/src/data/itineraryGeocoded.js', 'japan2026-mobile/src/data/itineraryGeocoded.js']) {
    fs.writeFileSync(P(rel), body);
  }
  console.log(`geocoded ${Object.keys(out).length}/${Object.keys(queries).length}; wrote itineraryGeocoded.js to all 3 data dirs`);
  if (fails.length) console.log('\nskipped:\n' + fails.join('\n'));
}

await (process.argv.includes('--worklist') ? worklist() : geocode());
